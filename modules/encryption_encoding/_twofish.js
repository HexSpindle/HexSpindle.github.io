function gfMult(a, b, poly) {
  let result = 0;
  while (b) {
    if (b & 1) result ^= a;
    a <<= 1;
    if (a & 0x100) a ^= poly;
    b >>>= 1;
  }
  return result & 0xff;
}

function mdsMultiply(x) {
  const b0 = x & 0xff, b1 = (x >>> 8) & 0xff, b2 = (x >>> 16) & 0xff, b3 = (x >>> 24) & 0xff;
  const r0 = gfMult(b0, 0x01, 0x169) ^ gfMult(b1, 0xef, 0x169) ^ gfMult(b2, 0x5b, 0x169) ^ gfMult(b3, 0x5b, 0x169);
  const r1 = gfMult(b0, 0x5b, 0x169) ^ gfMult(b1, 0xef, 0x169) ^ gfMult(b2, 0xef, 0x169) ^ gfMult(b3, 0x01, 0x169);
  const r2 = gfMult(b0, 0xef, 0x169) ^ gfMult(b1, 0x5b, 0x169) ^ gfMult(b2, 0x01, 0x169) ^ gfMult(b3, 0xef, 0x169);
  const r3 = gfMult(b0, 0xef, 0x169) ^ gfMult(b1, 0x01, 0x169) ^ gfMult(b2, 0xef, 0x169) ^ gfMult(b3, 0x5b, 0x169);
  return ((r3 << 24) | (r2 << 16) | (r1 << 8) | r0) >>> 0;
}

function rsMultiply(key8) {
  let result = 0;
  for (let i = 0; i < 4; i++) {
    let x = 0;
    for (let j = 0; j < 8; j++) x ^= gfMult(RS[i][j], key8[j], 0x14d);
    result |= x << (i * 8);
  }
  return result >>> 0;
}

function h(x, L, k) {
  const y = [x & 0xff, (x >>> 8) & 0xff, (x >>> 16) & 0xff, (x >>> 24) & 0xff];
  if (k === 4) {
    y[0] = Q1[y[0]] ^ (L[3] & 0xff);
    y[1] = Q0[y[1]] ^ ((L[3] >>> 8) & 0xff);
    y[2] = Q0[y[2]] ^ ((L[3] >>> 16) & 0xff);
    y[3] = Q1[y[3]] ^ ((L[3] >>> 24) & 0xff);
  }
  if (k >= 3) {
    y[0] = Q1[y[0]] ^ (L[2] & 0xff);
    y[1] = Q1[y[1]] ^ ((L[2] >>> 8) & 0xff);
    y[2] = Q0[y[2]] ^ ((L[2] >>> 16) & 0xff);
    y[3] = Q0[y[3]] ^ ((L[2] >>> 24) & 0xff);
  }
  y[0] = Q0[Q0[y[0]] ^ (L[1] & 0xff)] ^ (L[0] & 0xff);
  y[1] = Q0[Q1[y[1]] ^ ((L[1] >>> 8) & 0xff)] ^ ((L[0] >>> 8) & 0xff);
  y[2] = Q1[Q0[y[2]] ^ ((L[1] >>> 16) & 0xff)] ^ ((L[0] >>> 16) & 0xff);
  y[3] = Q1[Q1[y[3]] ^ ((L[1] >>> 24) & 0xff)] ^ ((L[0] >>> 24) & 0xff);
  y[0] = Q1[y[0]]; y[1] = Q0[y[1]]; y[2] = Q1[y[2]]; y[3] = Q0[y[3]];
  return mdsMultiply((y[3] << 24) | (y[2] << 16) | (y[1] << 8) | y[0]);
}

function ROL(x, n) { return ((x << n) | (x >>> (32 - n))) >>> 0; }
function ROR(x, n) { return ((x >>> n) | (x << (32 - n))) >>> 0; }

export function twofishKeySchedule(key) {
  const keyLen = key.length;
  if (keyLen !== 16 && keyLen !== 24 && keyLen !== 32) throw new Error(`Twofish key must be 16, 24 or 32 bytes (got ${keyLen})`);
  const k = keyLen / 8;
  const Me = new Array(k), Mo = new Array(k);
  for (let i = 0; i < k; i++) {
    const off = i * 8;
    Me[i] = (key[off] | (key[off + 1] << 8) | (key[off + 2] << 16) | (key[off + 3] << 24)) >>> 0;
    Mo[i] = (key[off + 4] | (key[off + 5] << 8) | (key[off + 6] << 16) | (key[off + 7] << 24)) >>> 0;
  }
  const S = new Array(k);
  for (let i = 0; i < k; i++) {
    const off = (k - 1 - i) * 8;
    S[i] = rsMultiply(key.slice(off, off + 8));
  }
  const subkeys = new Array(40);
  const rho = 0x01010101;
  for (let i = 0; i < 20; i++) {
    const A = h((2 * i * rho) >>> 0, Me, k);
    const B = ROL(h(((2 * i + 1) * rho) >>> 0, Mo, k), 8);
    subkeys[2 * i] = (A + B) >>> 0;
    subkeys[2 * i + 1] = ROL((A + 2 * B) >>> 0, 9);
  }
  return { subkeys, S, k };
}

function g(x, S, k) { return h(x, S, k); }

function readWordsLE(block) {
  return [
    (block[0] | (block[1] << 8) | (block[2] << 16) | (block[3] << 24)) >>> 0,
    (block[4] | (block[5] << 8) | (block[6] << 16) | (block[7] << 24)) >>> 0,
    (block[8] | (block[9] << 8) | (block[10] << 16) | (block[11] << 24)) >>> 0,
    (block[12] | (block[13] << 8) | (block[14] << 16) | (block[15] << 24)) >>> 0,
  ];
}
function writeWordsLE(a, b, c, d) {
  const out = new Uint8Array(16);
  const dv = new DataView(out.buffer);
  dv.setUint32(0, a, true); dv.setUint32(4, b, true); dv.setUint32(8, c, true); dv.setUint32(12, d, true);
  return out;
}

export function twofishEncryptBlock(block, ks) {
  const { subkeys, S, k } = ks;
  let [R0, R1, R2, R3] = readWordsLE(block);
  R0 ^= subkeys[0]; R1 ^= subkeys[1]; R2 ^= subkeys[2]; R3 ^= subkeys[3];
  for (let r = 0; r < 16; r += 2) {
    let T0 = g(R0, S, k);
    let T1 = g(ROL(R1, 8), S, k);
    R2 = ROR(R2 ^ ((T0 + T1 + subkeys[8 + 2 * r]) >>> 0), 1);
    R3 = ROL(R3, 1) ^ ((T0 + 2 * T1 + subkeys[9 + 2 * r]) >>> 0);
    T0 = g(R2, S, k);
    T1 = g(ROL(R3, 8), S, k);
    R0 = ROR(R0 ^ ((T0 + T1 + subkeys[8 + 2 * r + 2]) >>> 0), 1);
    R1 = ROL(R1, 1) ^ ((T0 + 2 * T1 + subkeys[9 + 2 * r + 2]) >>> 0);
  }
  R2 ^= subkeys[4]; R3 ^= subkeys[5]; R0 ^= subkeys[6]; R1 ^= subkeys[7];
  return writeWordsLE(R2 >>> 0, R3 >>> 0, R0 >>> 0, R1 >>> 0);
}

export function twofishDecryptBlock(block, ks) {
  const { subkeys, S, k } = ks;
  let [R0, R1, R2, R3] = readWordsLE(block);
  R0 ^= subkeys[4]; R1 ^= subkeys[5]; R2 ^= subkeys[6]; R3 ^= subkeys[7];
  for (let r = 14; r >= 0; r -= 2) {
    let T0 = g(R0, S, k);
    let T1 = g(ROL(R1, 8), S, k);
    R2 = ROL(R2, 1) ^ ((T0 + T1 + subkeys[8 + 2 * r + 2]) >>> 0);
    R3 = ROR(R3 ^ ((T0 + 2 * T1 + subkeys[9 + 2 * r + 2]) >>> 0), 1);
    T0 = g(R2, S, k);
    T1 = g(ROL(R3, 8), S, k);
    R0 = ROL(R0, 1) ^ ((T0 + T1 + subkeys[8 + 2 * r]) >>> 0);
    R1 = ROR(R1 ^ ((T0 + 2 * T1 + subkeys[9 + 2 * r]) >>> 0), 1);
  }
  R2 ^= subkeys[0]; R3 ^= subkeys[1]; R0 ^= subkeys[2]; R1 ^= subkeys[3];
  return writeWordsLE(R2 >>> 0, R3 >>> 0, R0 >>> 0, R1 >>> 0);
}

