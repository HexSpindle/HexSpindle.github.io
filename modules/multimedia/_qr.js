export const GF_EXP = new Uint8Array(512);
export const GF_LOG = new Uint8Array(256);
(function initGF() {
  let x = 1;
  for (let i = 0; i < 255; i++) {
    GF_EXP[i] = x; GF_LOG[x] = i;
    x <<= 1;
    if (x & 0x100) x ^= 0x11d;
  }
  for (let i = 255; i < 512; i++) GF_EXP[i] = GF_EXP[i - 255];
})();
export const gfMul = (a, b) => (a === 0 || b === 0) ? 0 : GF_EXP[GF_LOG[a] + GF_LOG[b]];

function rsGeneratorPoly(degree) {
  let poly = [1];
  for (let i = 0; i < degree; i++) {
    const next = new Array(poly.length + 1).fill(0);
    for (let j = 0; j < poly.length; j++) {
      next[j] ^= poly[j];
      next[j + 1] ^= gfMul(poly[j], GF_EXP[i]);
    }
    poly = next;
  }
  return poly;
}
const genCache = new Map();
function rsEncode(data, ecLen) {
  let gen = genCache.get(ecLen);
  if (!gen) { gen = rsGeneratorPoly(ecLen); genCache.set(ecLen, gen); }
  const res = new Uint8Array(ecLen);
  for (const d of data) {
    const factor = d ^ res[0];
    res.copyWithin(0, 1);
    res[ecLen - 1] = 0;
    if (factor !== 0) for (let i = 0; i < ecLen; i++) res[i] ^= gfMul(gen[i + 1], factor);
  }
  return res;
}

class BitBuffer {
  constructor() { this.bits = []; }
  push(val, len) { for (let i = len - 1; i >= 0; i--) this.bits.push((val >> i) & 1); }
  get length() { return this.bits.length; }
}

function charCountBits(version) { return version <= 9 ? 8 : 16; }

function pickVersion(dataLen, ecLevel) {
  for (let v = 1; v <= 40; v++) {
    const capacityBits = ECC_TABLE[v - 1][ecLevel].reduce((s, [n, , d]) => s + n * d, 0) * 8;
    const needed = 4 + charCountBits(v) + dataLen * 8;
    if (capacityBits >= needed) return v;
  }
  return null;
}

function buildCodewords(bytes, version, ecLevel) {
  const blocks = ECC_TABLE[version - 1][ecLevel];
  const capacityBits = blocks.reduce((s, [n, , d]) => s + n * d, 0) * 8;
  const buf = new BitBuffer();
  buf.push(4, 4); // byte mode indicator
  buf.push(bytes.length, charCountBits(version));
  for (const b of bytes) buf.push(b, 8);
  const termLen = Math.min(capacityBits - buf.length, 4);
  if (termLen > 0) buf.push(0, termLen);
  buf.push(0, 8 - (buf.length % 8)); // pad to the next codeword boundary (always 1-8 bits)
  const dataCodewords = [];
  for (let i = 0; i < buf.length; i += 8) {
    let b = 0;
    for (let j = 0; j < 8; j++) b = (b << 1) | buf.bits[i + j];
    dataCodewords.push(b);
  }
  const pad = [0xec, 0x11];
  let p = 0;
  while (dataCodewords.length * 8 < capacityBits) dataCodewords.push(pad[p++ % 2]);

  const dataBlocks = [], ecBlocks = [];
  let idx = 0;
  for (const [numBlocks, total, data] of blocks) {
    const ecLen = total - data;
    for (let i = 0; i < numBlocks; i++) {
      const block = dataCodewords.slice(idx, idx + data);
      idx += data;
      dataBlocks.push(block);
      ecBlocks.push(Array.from(rsEncode(block, ecLen)));
    }
  }
  const out = [];
  const maxData = Math.max(...dataBlocks.map(b => b.length));
  for (let i = 0; i < maxData; i++) for (const b of dataBlocks) if (i < b.length) out.push(b[i]);
  const maxEc = Math.max(...ecBlocks.map(b => b.length));
  for (let i = 0; i < maxEc; i++) for (const b of ecBlocks) if (i < b.length) out.push(b[i]);

  const bits = new BitBuffer();
  for (const cw of out) bits.push(cw, 8);
  return bits.bits;
}

export const MASK_FUNCS = [
  (i, j) => (i + j) % 2 === 0,
  (i, j) => i % 2 === 0,
  (i, j) => j % 3 === 0,
  (i, j) => (i + j) % 3 === 0,
  (i, j) => (Math.floor(i / 2) + Math.floor(j / 3)) % 2 === 0,
  (i, j) => ((i * j) % 2) + ((i * j) % 3) === 0,
  (i, j) => (((i * j) % 2) + ((i * j) % 3)) % 2 === 0,
  (i, j) => (((i + j) % 2) + ((i * j) % 3)) % 2 === 0,
];

function maskPenalty(m, size) {
  let n1 = 0, n2 = 0, n3 = 0;
  const n3pat = [1, 0, 1, 1, 1, 0, 1];
  const matches = (seq, start) => n3pat.every((v, k) => seq[start + k] === v);
  const findOccurrences = (seq) => {
    let count = 0;
    for (let idx = 0; idx <= seq.length - 7; idx++) {
      if (!matches(seq, idx)) continue;
      const before = seq.slice(Math.max(idx - 4, 0), idx);
      const after = seq.slice(idx + 7, Math.min(idx + 11, seq.length));
      const lightBefore = idx === 0 || before.every(v => v === 0);
      const lightAfter = idx === seq.length - 7 || after.every(v => v === 0);
      if (idx === 0 || idx === seq.length - 7 || lightBefore || lightAfter) count += 40;
    }
    return count;
  };
  let lastRow = null;
  const col = new Array(size);
  for (let i = 0; i < size; i++) {
    const row = m[i];
    let rowRun = 1, colRun = 1;
    for (let j = 0; j < size; j++) {
      col[j] = m[j][i];
      if (j > 0) {
        if (row[j] === row[j - 1]) rowRun++; else { if (rowRun >= 5) n1 += rowRun - 2; rowRun = 1; }
      }
    }
    for (let j = 0; j < size; j++) {
      if (j > 0 && col[j] === col[j - 1]) colRun++; else if (j > 0) { if (colRun >= 5) n1 += colRun - 2; colRun = 1; }
    }
    if (rowRun >= 5) n1 += rowRun - 2;
    if (colRun >= 5) n1 += colRun - 2;
    if (lastRow) for (let j = 1; j < size; j++) {
      if (row[j] === row[j - 1] && row[j] === lastRow[j] && row[j] === lastRow[j - 1]) n2 += 3;
    }
    lastRow = row;
    n3 += findOccurrences(row) + findOccurrences(col);
  }
  let dark = 0;
  for (let i = 0; i < size; i++) for (let j = 0; j < size; j++) dark += m[i][j];
  const percent = (dark * 100) / (size * size);
  const n4 = 10 * Math.floor(Math.abs(percent - 50) / 5);
  return n1 + n2 + n3 + n4;
}

export function buildFunctionPatterns(size, version) {
  const matrix = Array.from({ length: size }, () => new Array(size).fill(2));
  const isFunction = Array.from({ length: size }, () => new Array(size).fill(false));

  const setFn = (i, j, v) => { matrix[i][j] = v; isFunction[i][j] = true; };

  const corners = [[0, 0], [0, size - 8], [size - 8, 0]];
  for (const [bi, bj] of corners) {
    const offset = bi === 0 ? 1 : 0;
    const sepOffset = bj !== 0 ? 0 : 1;
    for (let r = 0; r < 8; r++) for (let c = 0; c < 8; c++) {
      setFn(bi + r, bj + c, FINDER_PATTERN[offset + r][sepOffset + c]);
    }
  }

  for (let i = 8; i < size - 8; i++) {
    const bit = i % 2 === 0 ? 1 : 0;
    setFn(6, i, bit);
    setFn(i, 6, bit);
  }

  if (version >= 2) {
    const positions = ALIGNMENT_POS[version - 2];
    const minP = positions[0], maxP = positions[positions.length - 1];
    const finderCenters = new Set([`${minP},${minP}`, `${minP},${maxP}`, `${maxP},${minP}`]);
    for (const x of positions) for (const y of positions) {
      if (finderCenters.has(`${x},${y}`)) continue;
      for (let r = 0; r < 5; r++) for (let c = 0; c < 5; c++) {
        setFn(x - 2 + r, y - 2 + c, ALIGNMENT_PATTERN[r][c]);
      }
    }
  }

  for (let i = 0; i < 9; i++) {
    if (!isFunction[i][8]) setFn(i, 8, 0);
    if (!isFunction[8][i]) setFn(8, i, 0);
  }
  for (let i = 0; i < 8; i++) {
    if (!isFunction[size - 1 - i][8]) setFn(size - 1 - i, 8, 0);
    if (!isFunction[8][size - 1 - i]) setFn(8, size - 1 - i, 0);
  }
  if (version >= 7) {
    for (let i = 0; i < 6; i++) for (let j = 0; j < 3; j++) {
      setFn(size - 11 + j, i, 0);
      setFn(i, size - 11 + j, 0);
    }
  }

  return { matrix, isFunction };
}

export function zigzagPositions(size, isFunction) {
  const positions = [];
  for (let rightBase = size - 1; rightBase > 0; rightBase -= 2) {
    const right = rightBase <= 6 ? rightBase - 1 : rightBase;
    for (let vertical = 0; vertical < size; vertical++) {
      for (let z = 0; z < 2; z++) {
        const j = right - z;
        let upwards = (right & 2) === 0;
        if (j < 6) upwards = !upwards;
        const i = upwards ? size - 1 - vertical : vertical;
        if (!isFunction[i][j]) positions.push([i, j]);
      }
    }
  }
  return positions;
}

export function buildQrMatrix(text, ecLevel = 'M') {
  const bytes = new TextEncoder().encode(text);
  const version = pickVersion(bytes.length, ecLevel);
  if (version === null) throw new Error('Input text is too long to fit in a QR code');
  const size = version * 4 + 17;
  const { matrix, isFunction } = buildFunctionPatterns(size, version);

  const codewordBits = buildCodewords(bytes, version, ecLevel);
  let idx = 0;
  for (const [i, j] of zigzagPositions(size, isFunction)) {
    matrix[i][j] = idx < codewordBits.length ? codewordBits[idx++] : 0;
  }

  let best = null, bestScore = Infinity, bestMask = 0;
  for (let m = 0; m < 8; m++) {
    const maskFn = MASK_FUNCS[m];
    const candidate = matrix.map((row, i) => row.map((v, j) => isFunction[i][j] ? v : (v ^ (maskFn(i, j) ? 1 : 0))));
    const score = maskPenalty(candidate, size);
    if (score < bestScore) { bestScore = score; best = candidate; bestMask = m; }
  }

  const fmtBits = FORMAT_INFO[(EC_BITS[ecLevel] << 3) | bestMask];
  let voffset = 0, hoffset = 0;
  for (let i = 0; i < 8; i++) {
    const vbit = (fmtBits >> i) & 1;
    const hbit = (fmtBits >> (14 - i)) & 1;
    if (i === 6) { voffset += 1; hoffset = 1; }
    best[i + voffset][8] = vbit;
    best[8][i + hoffset] = hbit;
    best[8][size - 1 - i] = vbit;
    best[size - 1 - i][8] = hbit;
  }
  best[size - 8][8] = 1;

  if (version >= 7) {
    const vinfo = VERSION_INFO[version - 7];
    for (let i = 0; i < 6; i++) for (let b = 0; b < 3; b++) {
      const bit = (vinfo >> (i * 3 + b)) & 1;
      best[size - 11 + b][i] = bit;
      best[i][size - 11 + b] = bit;
    }
  }

  return { matrix: best, size, version, mask: bestMask };
}

export function qrMatrixToSvg(matrix, size, moduleSize, margin) {
  const dim = size + margin * 2;
  const px = dim * moduleSize;
  let path = '';
  for (let i = 0; i < size; i++) for (let j = 0; j < size; j++) {
    if (matrix[i][j]) path += `M${(j + margin) * moduleSize},${(i + margin) * moduleSize}h${moduleSize}v${moduleSize}h-${moduleSize}z`;
  }
  return `<?xml version="1.0" encoding="UTF-8"?>\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${px} ${px}" width="${px}" height="${px}" shape-rendering="crispEdges"><rect width="${px}" height="${px}" fill="#fff"/><path d="${path}" fill="#000"/></svg>`;
}
